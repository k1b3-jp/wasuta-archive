-- First editorial workflow vertical: milestones must transition through RPCs.

create table public.archive_audit_log (
  audit_id bigint generated by default as identity primary key,
  entity_type text not null,
  entity_id bigint not null,
  action text not null,
  from_status text,
  to_status text,
  actor_id uuid not null,
  reason text,
  created_at timestamptz not null default now()
);

alter table public.archive_audit_log enable row level security;

create policy archive_audit_log_select_reviewer
  on public.archive_audit_log for select to authenticated
  using (public.has_role_at_least('reviewer'));

drop policy if exists milestones_write_editor on public.milestones;
drop policy if exists occurrences_write_editor on public.timeline_occurrences;

create policy milestones_select_editor
  on public.milestones for select to authenticated
  using (public.has_role_at_least('viewer'));

create policy milestones_insert_draft_editor
  on public.milestones for insert to authenticated
  with check (
    public.has_role_at_least('editor')
    and status = 'draft'
  );

create policy milestones_update_draft_editor
  on public.milestones for update to authenticated
  using (
    public.has_role_at_least('editor')
    and status = 'draft'
  )
  with check (
    public.has_role_at_least('editor')
    and status = 'draft'
  );

create policy milestones_delete_draft_editor
  on public.milestones for delete to authenticated
  using (
    public.has_role_at_least('editor')
    and status = 'draft'
  );

create policy occurrences_select_editor
  on public.timeline_occurrences for select to authenticated
  using (public.has_role_at_least('viewer'));

create policy occurrences_insert_draft_editor
