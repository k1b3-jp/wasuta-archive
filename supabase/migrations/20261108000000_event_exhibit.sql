-- Additive, source-backed exhibit passages. No research material is published here.
create table public.event_exhibit_cards (
  card_id bigint generated by default as identity primary key,
  research_key text not null unique,
  event_id integer not null references public.events(event_id) on delete restrict,
  source_id bigint not null references public.sources(source_id) on delete restrict,
  member_id bigint references public.members(member_id) on delete restrict,
  speaker text not null check (length(btrim(speaker)) > 0),
  phase text not null check (phase in ('before','day','after','recollection')),
  relation_kind text not null check (relation_kind in ('announcement','performance_report','reflection')),
  summary text not null check (length(btrim(summary)) > 0),
  locator text not null check (length(btrim(locator)) > 0),
  published_on date,
  published_at timestamptz,
  date_precision text not null check (date_precision in ('day','instant','unknown')),
  original_date_label text,
  original_publication_confirmed boolean not null default false,
  usage_status text not null default 'link_only' check (usage_status = 'link_only'),
  verification_status text not null default 'unverified' check (verification_status in ('unverified','verified','rejected')),
  status text not null default 'draft' check (status in ('draft','review','published','withdrawn')),
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((date_precision = 'unknown' and published_on is null and published_at is null)
    or (date_precision = 'day' and published_on is not null and published_at is null)
    or (date_precision = 'instant' and published_on is not null and published_at is not null
      and (published_at at time zone 'Asia/Tokyo')::date = published_on)),
  check (status <> 'published' or (verification_status='verified' and reviewed_by is not null and reviewed_at is not null))
);
create index event_exhibit_cards_event on public.event_exhibit_cards(event_id, published_on);
alter table public.event_exhibit_cards enable row level security;
create policy exhibit_read on public.event_exhibit_cards for select to anon, authenticated using (
  (status='published' and verification_status='verified' and exists (
    select 1 from public.event_sources es where es.event_id=event_exhibit_cards.event_id
    and es.source_id=event_exhibit_cards.source_id and es.fact_kind='exhibit' and es.verification_status='verified'
  )) or (current_user='authenticated' and public.has_role_at_least('editor'))
);
grant select on public.event_exhibit_cards to anon, authenticated;
revoke insert,update,delete on public.event_exhibit_cards from anon,authenticated;

-- Editors can revise only unpublished passages; all mutations are audited.
create function public.save_event_exhibit_draft(payload jsonb) returns bigint
language plpgsql security definer set search_path = public, pg_temp as $$
declare saved_id bigint;
begin
  if not public.has_role_at_least('editor') then raise exception 'editor required' using errcode='42501'; end if;
  insert into public.event_exhibit_cards(research_key,event_id,source_id,member_id,speaker,phase,relation_kind,summary,locator,published_on,published_at,date_precision,original_date_label,original_publication_confirmed)
  values(payload->>'research_key',(payload->>'event_id')::integer,(payload->>'source_id')::bigint,(payload->>'member_id')::bigint,payload->>'speaker',payload->>'phase',payload->>'relation_kind',payload->>'summary',payload->>'locator',(payload->>'published_on')::date,(payload->>'published_at')::timestamptz,payload->>'date_precision',payload->>'original_date_label',coalesce((payload->>'original_publication_confirmed')::boolean,false))
  on conflict(research_key) do update set
    source_id=excluded.source_id, member_id=excluded.member_id, speaker=excluded.speaker,
    phase=excluded.phase,relation_kind=excluded.relation_kind,summary=excluded.summary,locator=excluded.locator,
    published_on=excluded.published_on,published_at=excluded.published_at,date_precision=excluded.date_precision,
    original_date_label=excluded.original_date_label,original_publication_confirmed=excluded.original_publication_confirmed,
    status='draft',verification_status='unverified',reviewed_by=null,reviewed_at=null,updated_at=now()
  where event_exhibit_cards.status in ('draft','review','withdrawn') and event_exhibit_cards.event_id=excluded.event_id
  returning card_id into saved_id;
  if saved_id is null then raise exception 'published passage must be withdrawn before revision' using errcode='22023'; end if;
  insert into public.archive_audit_log(entity_type,entity_id,action,to_status,actor_id)
    values('event_exhibit',saved_id,'save_draft','draft',auth.uid());
  return saved_id;
end $$;

create function public.transition_event_exhibit(target_id bigint, next_status text, reason text) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare card public.event_exhibit_cards; required_role text;
begin
  required_role := case when next_status='review' then 'editor' else 'reviewer' end;
  if not public.has_role_at_least(required_role) then raise exception 'insufficient role' using errcode='42501'; end if;
  if nullif(btrim(reason),'') is null then raise exception 'review reason required' using errcode='22023'; end if;
  select * into strict card from public.event_exhibit_cards where card_id=target_id for update;
  if not ((card.status in ('draft','withdrawn') and next_status='review') or
    (card.status='review' and next_status in ('draft','published')) or
    (card.status='published' and next_status='withdrawn')) then
    raise exception 'invalid transition' using errcode='22023';
  end if;
  if next_status='published' then
    if not exists(select 1 from public.sources where source_id=card.source_id and url ~ '^https://[^[:space:]]+$') then
      raise exception 'safe source required' using errcode='22023'; end if;
    if not exists(select 1 from public.event_sources where event_id=card.event_id and source_id=card.source_id
      and fact_kind='exhibit' and verification_status='verified' and verified_by is not null and verified_at is not null) then
      raise exception 'verified typed event source required' using errcode='22023'; end if;
  end if;
  update public.event_exhibit_cards set status=next_status,
    verification_status=case when next_status='published' then 'verified' else 'unverified' end,
    reviewed_by=case when next_status='published' then auth.uid() end,
    reviewed_at=case when next_status='published' then now() end,updated_at=now() where card_id=target_id;
  insert into public.archive_audit_log(entity_type,entity_id,action,from_status,to_status,actor_id,reason)
    values('event_exhibit',target_id,'transition',card.status,next_status,auth.uid(),btrim(reason));
end $$;
revoke all on function public.save_event_exhibit_draft(jsonb) from public;
revoke all on function public.transition_event_exhibit(bigint,text,text) from public;
grant execute on function public.save_event_exhibit_draft(jsonb),public.transition_event_exhibit(bigint,text,text) to authenticated;

-- Human reviewers explicitly verify the passage's typed evidence before publication.
create function public.review_event_exhibit_evidence(target_id bigint, review_reason text) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare card public.event_exhibit_cards;
begin
  if not public.has_role_at_least('reviewer') then raise exception 'reviewer required' using errcode='42501'; end if;
  if nullif(btrim(review_reason),'') is null then raise exception 'review reason required' using errcode='22023'; end if;
  select * into strict card from public.event_exhibit_cards where card_id=target_id for update;
  if card.status <> 'review' then raise exception 'review passage required' using errcode='22023'; end if;
  insert into public.event_sources(event_id,source_id,fact_kind,verification_status,verified_by,verified_at,note)
    values(card.event_id,card.source_id,'exhibit','verified',auth.uid(),now(),btrim(review_reason))
    on conflict(event_id,source_id,fact_kind) do update set verification_status='verified',verified_by=auth.uid(),verified_at=now(),note=excluded.note;
  insert into public.archive_audit_log(entity_type,entity_id,action,from_status,to_status,actor_id,reason)
    values('event_exhibit',target_id,'verify_evidence',card.status,card.status,auth.uid(),btrim(review_reason));
end $$;
revoke all on function public.review_event_exhibit_evidence(bigint,text) from public;
grant execute on function public.review_event_exhibit_evidence(bigint,text) to authenticated;
